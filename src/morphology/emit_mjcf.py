def _emit_wrist_tensegrity(worldbody, ulna, shoulder: CompiledShoulder, morph):
    """Emit the wrist's strut pair and return the body the manus should hang on.

    Proximal strut is rigid on the ulna. Distal strut is a worldbody child with a
    free joint — MuJoCo permits those only at the top level, which is precisely
    why this is a tensegrity joint and not a compliant hinge: nothing structural
    reaches the hand, only tendons.
    """
    wrist = shoulder.wrist
    prefix = shoulder.side
    proximal = _emit_strut_body(
        ulna,
        f"{prefix}_wrist_proximal",
        wrist.proximal_geom,
        wrist.proximal_pos,
        wrist.proximal_quat,
        joint="fixed",
    )
    distal = _emit_strut_body(
        worldbody,
        f"{prefix}_wrist_distal",
        wrist.distal_geom,
        wrist.distal_pos,
        wrist.distal_quat,
        joint="free",
    )
    del proximal
    return distal


def _emit_bone_wing(parent: ET.Element, shoulder: CompiledShoulder, morph,
                    worldbody: ET.Element | None = None) -> None:
    """Humerus / ulna / manus chain hanging off the mobile strut.

    The humerus is a rigid child of the strut — the tensegrity network is its
    shoulder joint, same as the plate wing — with one twist hinge about the span
    for feathering. Elbow and wrist are plain hinges about the wing-plane normal,
    so the wing folds inside its own plane the way a bird's does.

    Bone-local frame: +z spans out to the tip, +x is chord (toward the trailing
    edge, so -x is cranial), +y is the wing normal. Elbow and wrist hinge about
    opposite normals so they counter-rotate: in the reference plate the elbow is
    the caudal apex and the wrist the cranial one, and same-sign hinges spiral
    the chain into a C instead of folding it into the avian Z.

    The R side is the exact y-mirror of L: every offset here is y-free, so only
    the mount quaternion mirrors and the twist axis flips sign (a_R = -M a_L,
    which leaves the two wing-normal hinges unchanged — the same rule the plate
    wing's pitch hinge follows).
    """
    b = morph.wing.bones
    prefix = shoulder.side
    b_wrist_manus_pos = shoulder.wrist.manus_pos if shoulder.wrist else None
    b_wrist_manus_quat = shoulder.wrist.manus_quat if shoulder.wrist else None
    quat = b.mount_quat()
    if prefix == "R":
        quat = mirror_quat_wxyz(quat)
    twist_axis = "0 0 1" if prefix == "L" else "0 0 -1"
    # Feather vanes are the one thing here with an offset off the y=0 plane, so
    # they are also the one thing that has to mirror explicitly (p_R = M p_L).
    y_sign = 1.0 if prefix == "L" else -1.0

    def hinge(body, name, axis, rng):
        ET.SubElement(
            body,
            "joint",
            name=f"{prefix}_{name}",
            type="hinge",
            axis=axis,
            limited="true",
            range=_vec2(rng),
            damping=str(b.damping),
            armature=str(b.armature),
            # The shoulder-joint class default frictionloss=0.1 N m is ~1000x the
            # torque these gram-scale bones see; it would stiction-lock the fold.
            frictionloss="0",
        )

    def bone(body, name, z0, z1, radius, mass, dx=0.0):
        ET.SubElement(
            body,
            "geom",
            name=f"{prefix}_{name}",
            type="capsule",
            fromto=f"{dx} 0 {z0} {dx} 0 {z1}",
            size=str(radius),
            mass=str(mass),
            rgba=BONE_RGBA,
            contype="0",
            conaffinity="0",
            group="2",
        )

    def feathers(body, tag, count, z0, z1, len0, len1, rake0, rake1, width, rgba, group=0):
        """Fan ``count`` flat vanes off a bone, rooted at successive span stations.

        ``rake`` is the angle of the shaft off the span axis toward the trailing
        edge: ~24 deg on the outermost primary (it continues the wingtip) up to
        ~95 deg on a secondary (straight aft). Sweeping the rake across the manus
        is what gives an eagle its separated, fingered tip rather than one slab.
        Keep it under 90: past that the vane's own axis points back inboard, and
        the root feather reaches through the strut and across the midline.

        Vanes are shingled along the wing normal by ``_SHINGLE`` per index, the
        outer lying over the next one in, as a bird's do. Emitting them all at
        y=0 makes them exactly coplanar, which z-fights into streaks and a
        staircased trailing edge — the whole fan is only 0.8 mm thick.

        Returns the bone-local tip of the last vane.
        """
        # Each fan restarts its shingle, so offset the groups by a third of a step
        # to keep every vane on its own plane -- two vanes at the same y anywhere
        # on the wing z-fight wherever they overlap.
        base = _SHINGLE * group / 3.0
        tip = (0.0, y_sign * (base + _SHINGLE * max(count - 1, 0)), z1)
        for i in range(count):
            t = 0.0 if count == 1 else i / (count - 1)
            rake = rake0 + t * (rake1 - rake0)
            length = len0 + t * (len1 - len0)
            root_z = z0 + t * (z1 - z0)
            lift = y_sign * (base + _SHINGLE * i)
            # Rotating +z about +y by `rake` gives (sin, 0, cos): out along the
            # span and aft. The vane's long axis is its own local z.
            d = (math.sin(rake), 0.0, math.cos(rake))
            name = f"{prefix}_{tag}_{i + 1:02d}"
            if b.feathers is not None:
                # Each link is a body turned so its own +z runs out along the
                # shaft, which leaves `lift` as the geom's only offset — still
                # the shingle, and still one plane per feather.
                _emit_vane(body, name, root_z, rake, length, lift, width,
                           0.02 * b.mass, rgba, b.feathers)
            else:
                ET.SubElement(
                    body,
                    "geom",
                    name=name,
                    type="box",
                    pos=f"{0.5 * length * d[0]} {lift} {root_z + 0.5 * length * d[2]}",
                    euler=f"0 {rake} 0",
                    size=f"{0.5 * width} 0.0004 {0.5 * length}",
                    mass=str(0.02 * b.mass),
                    rgba=rgba,
                    contype="0",
                    conaffinity="0",
                    group="2",
                )
            tip = (length * d[0], lift, root_z + length * d[2])
        return tip

    humerus = ET.SubElement(
        parent,
        "body",
        name=f"{prefix}_humerus",
        pos=_vec3(shoulder.mobile_geom.midpoint),
        childclass="shoulder-joint",
        quat=_vec4(quat),
    )
    hinge(humerus, "humerus_twist", twist_axis, b.twist_range_rad)
    bone(humerus, "humerus", 0.0, b.humerus, 0.0030, 0.40 * b.mass)
    ET.SubElement(
        humerus,
        "geom",
        name=f"{prefix}_humerus_head",
        type="sphere",
        pos="0 0 0",
        size="0.0042",
        mass=str(0.05 * b.mass),
        rgba=BONE_RGBA,
        contype="0",
        conaffinity="0",
        group="2",
    )
    # Tertials: the innermost flight feathers, filling the gap in to the body.
    # Rake stays under 90 deg — past it the vane points back inboard, and the
    # root one then reaches through the strut and across the midline.
    feathers(humerus, "tertial", 3, 0.46 * b.humerus, 0.98 * b.humerus,
             0.95 * b.chord, 1.0 * b.chord, math.radians(88), math.radians(80),
             0.36 * b.chord, FEATHER_RGBA[0], group=0)

    ulna = ET.SubElement(humerus, "body", name=f"{prefix}_ulna", pos=f"0 0 {b.humerus}")
    hinge(ulna, "elbow", "0 1 0", b.elbow_range_rad)
    bone(ulna, "ulna", 0.0, b.ulna, 0.0024, 0.35 * b.mass)
    # The radius: the thin second forearm bone in the reference figure. Visual
    # only, but it is what makes the forearm read as a forearm and not a stick.
    bone(ulna, "radius", 0.0, b.ulna, 0.0013, 0.05 * b.mass, dx=-0.0052)
    feathers(ulna, "secondary", 7, 0.06 * b.ulna, 0.96 * b.ulna,
             1.0 * b.chord, 0.84 * b.chord, math.radians(95), math.radians(78),
             0.30 * b.chord, FEATHER_RGBA[0], group=1)

    if b.cables is not None:
        _emit_cable_anchors(prefix, b, humerus, ulna)

    wrist_host = None
    if b.wrist is not None:
        if worldbody is None:
            raise ValueError("a tensegrity wrist needs the worldbody to hang its free strut on")
        wrist_host = _emit_wrist_tensegrity(worldbody, ulna, shoulder, morph)

    if b.wrist is None:
        manus = ET.SubElement(ulna, "body", name=f"{prefix}_manus", pos=f"0 0 {b.ulna}")
        hinge(manus, "wrist", "0 -1 0", b.wrist_range_rad)
    else:
        # Tensegrity wrist: the hand leaves the kinematic chain. _emit_wrist put
        # the proximal strut on the ulna and the free distal strut in the
        # worldbody; the manus rides the latter, joined to the forearm by tendons
        # alone. No wrist joint exists to hinge or to servo.
        manus = ET.SubElement(
            wrist_host,
            "body",
            name=f"{prefix}_manus",
            pos=_vec3(b_wrist_manus_pos),
            quat=_vec4(b_wrist_manus_quat),
            childclass="shoulder-joint",
        )
    bone(manus, "carpometacarpus", 0.0, 0.62 * b.manus, 0.0019, 0.14 * b.mass)
    bone(manus, "phalanx", 0.62 * b.manus, b.manus, 0.0013, 0.06 * b.mass)
    # Primaries: long, separated, raked progressively forward toward the tip —
    # the eagle's fingered wingtip. The outermost one carries the wingtip marker.
    # rake1 stays well off the span: at 16 deg the outermost primary carried only
    # 33 mm of chord and the hand converged to a spike. An eagle's is blunt and
    # deeply slotted, so the outer feather keeps ~40 mm of chord on it.
    tip = feathers(manus, "primary", 8, 0.05 * b.manus, b.manus,
                   0.72 * b.primary, 1.0 * b.primary, math.radians(72), math.radians(24),
                   0.20 * b.chord, FEATHER_RGBA[1], group=2)
    if b.cables is not None:
        _cable_anchor_site(manus, prefix, "manus", b.cables.offset,
                           b.cables.manus_frac * b.manus)

    # Wingtip marker: the reference point every kinematic check measures.
    ET.SubElement(
        manus,
        "site",
        name=f"{prefix}_wingtip",
        type="sphere",
        pos=_vec3(tip),
        size="0.004",
        rgba="1 0.85 0.1 1",
        group="3",
    )


def _capsule(parent, name, p1, p2, radius, mass):
    # contype=2/conaffinity=1 is the standard self-collision filter: strut-vs-strut
    # is masked (2&1 == 0 both ways) so the interleaved tensegrity capsules don't
    # spawn hundreds of spurious MJX candidate pairs, while strut-vs-floor
    # (contype 1) still collides. The struts never actually touch in this rig, so
    # this only removes wasted broad-phase work (and gradient noise).
    ET.SubElement(
        parent,
        "geom",
        name=name,
        type="capsule",
        fromto=_vec6(p1, p2),
        size=str(radius),
        mass=str(mass),
        rgba="0.5 0.5 0.5 1",
        contype="2",
        conaffinity="1",
    )


def _site(parent, body_name, node_name, pos, quat=None):
    attrs = {
        "name": f"{body_name}_{node_name}",
        "pos": _vec3(pos),
        "size": "0.002",
        "rgba": "0.2 0.8 0.2 1",
        "group": "3",
    }
    if quat is not None:
        attrs["quat"] = _vec4(quat)
    ET.SubElement(parent, "site", **attrs)


def _emit_crank_disk(parent: ET.Element, disk_name: str, disk: Dict[str, Any], morph) -> None:
    spec = morph.motors.disk
    disk_rgba = MATPLOTLIB_BLUE_RGBA if disk_name.endswith("_t1") else MATPLOTLIB_ORANGE_RGBA
    pillar = ET.SubElement(
        parent,
        "body",
        name=f"{disk_name}_pillar",
        pos=_vec3(disk["pillar_pos"]),
    )
    ET.SubElement(
        pillar,
        "inertial",
        pos="0 0 0.11",
        mass="0.1",
        fullinertia="1e-4 1e-4 1e-4 0 0 0",
    )
    ET.SubElement(
        pillar,
        "geom",
        name=f"{disk_name}_pillar_geom",
        type="cylinder",
        size=f"{spec.pillar_radius} {spec.pillar_height / 2}",
        pos=f"0 0 {spec.pillar_height / 2}",
        rgba="0.4 0.4 0.4 0.8",
        contype="0",
        conaffinity="0",
        group="2",
    )
    euler = disk["euler"]
    disk_body = ET.SubElement(
        pillar,
        "body",
        name=f"{disk_name}_disk",
        pos=f"0 0 {spec.pillar_height}",
        euler=_vec3(euler),
    )
    ET.SubElement(
        disk_body,
        "joint",
        name=f"{disk_name}_disk_hinge",
        type="hinge",
        axis="0 0 1",
        damping="0.001",
        armature="0.0001",
    )
    ET.SubElement(
        disk_body,
        "inertial",
        pos="0 0 0",
        mass="0.005",
        fullinertia="1e-6 2e-6 1e-6 0 0 0",
    )
    ET.SubElement(
        disk_body,
        "geom",
        name=f"{disk_name}_disk_geom",
        type="cylinder",
        size=f"{spec.radius} {spec.disk_half_height}",
        rgba=disk_rgba,
        contype="0",
        conaffinity="0",
        group="2",
    )
    rim = disk["rim_pos"]
    # If the tendon pin sits past the disk rim (crank_throw > radius), draw a rigid
    # crank arm from the hinge axis out to the pin so the lever is physical.
    pin_r = float(np.linalg.norm(rim[:2]))
    if pin_r > spec.radius + 1e-6:
        ET.SubElement(
            disk_body,
            "geom",
            name=f"{disk_name}_crank_arm",
            type="capsule",
            fromto=f"0 0 0 {rim[0]} {rim[1]} {rim[2]}",
            size="0.0025",
            rgba=disk_rgba,
            contype="0",
            conaffinity="0",
            group="2",
        )
    ET.SubElement(
        disk_body,
        "site",
        name=f"crank_disks_{disk_name}",
        pos=_vec3(rim),
        size="0.002",
        rgba=disk["rim_rgba"],
        group="3",
    )
    cables = morph.wing.bones.cables if morph.wing.bones else None
    if cables is not None:
        # The wing cables get their own pin, clear of the motor tendon's. Off the
        # hinge axis on purpose: at radius zero the cable length stops depending on
        # crank angle and the motor stops driving the wing's shape at all.
        #
        # Mirrored exactly as the motor tendon's rim is (compile.py, where the R
        # disks are built): the R disk body is tilted -tilt where L is +tilt, so a
        # y-mirror of a disk-local point flips its y and leaves x alone. Giving
        # both sides the same local pin puts the R one on the wrong side of its
        # disk — 19 mm off its mirror position, which leaves the right cables
        # 17 mm short and flaps the right wing out of phase with the left.
        y_mirror = -1.0 if disk_name.startswith("R_") else 1.0
        pin = np.array([
            cables.pin_radius * math.cos(cables.pin_phase),
            y_mirror * cables.pin_radius * math.sin(cables.pin_phase),
            0.0,
        ])
        ET.SubElement(
            disk_body,
            "geom",
            name=f"{disk_name}_cable_arm",
            type="capsule",
            fromto=f"0 0 0 {pin[0]} {pin[1]} {pin[2]}",
            size="0.0016",
            rgba="0.15 0.85 0.4 1",
            contype="0",
            conaffinity="0",
            group="2",
        )
        ET.SubElement(
            disk_body,
            "site",
            name=f"{disk_name}_cable_pin",
            type="sphere",
            pos=_vec3(pin),
            size="0.0024",
            rgba="0.15 0.85 0.4 1",
            group="3",
        )


def _add_wing_cables(tendon_el, prefix: str, morph) -> None:
    """One cable per bone, each running from the bone in to a pin on a crank disk.

    That pin is off the disk's hinge axis, so every cable's length is a function
    of crank angle: the motors drive the wing's shape the same way they already
    drive the shoulder, instead of the wing being posed by a servo.

    They are emitted INERT — springlength as a wide range, which MuJoCo reads as
    "no force between these" — because a cable is only tensioned relative to a
    pose and the compiler has not got one. ``runtime.wing_cables.apply_tension``
    measures the compiled pose and writes the real rest length. A single-valued
    springlength here would be a two-sided spring against a placeholder number,
    which is ~110 N of nonsense shoving the wing off the rig.
    """
    c = morph.wing.bones.cables
    bones = (("humerus", c.disks[0]), ("ulna", c.disks[1]), ("manus", c.disks[2]))
    # Each cable rides in over the guide at the distal end of every bone inboard
    # of its own before it drops to the disk. Straight from the hand to the body
    # a cable hangs across open air and hauls the hand off the wrist cage; over
    # the forearm and the humerus it stays on the skeleton, and it gains a moment
    # arm at every joint it crosses instead of only at the shoulder.
    via = {
        "humerus": (),
        "ulna": ("guide_humerus",),
        "manus": ("guide_ulna", "guide_humerus"),
    }
    for bone, station in bones:
        spatial = ET.SubElement(
            tendon_el,
            "spatial",
            name=f"{prefix}_cable_{bone}",
            stiffness=str(c.stiffness),
            damping=str(c.damping),
            width=str(c.width),
            rgba="0.15 0.85 0.4 1",
            springlength="0 1e9",
        )
        ET.SubElement(spatial, "site", site=f"{prefix}_cable_{bone}")
        for guide in via[bone]:
            ET.SubElement(spatial, "site", site=f"{prefix}_cable_{guide}")
        ET.SubElement(spatial, "site", site=f"{prefix}_{station}_cable_pin")


def _add_wrist_tendons(tendon_el, shoulder: CompiledShoulder, morph,
                       color_structural_tendons: bool) -> None:
    """The wrist's own sigma-expanded net, same topology as the shoulder's.

    Materials come from the ``wrist:`` block rather than the shoulder's tendon
    defaults: this net is an order of magnitude smaller and holds the hand, not
    the whole wing, so it wants its own stiffness and pretension.
    """
    w = morph.wing.bones.wrist
    prefix = shoulder.side
    wrist = shoulder.wrist
    for index, edge in enumerate(wrist.structural_edges):
        ma = edge.anchor_a if edge.anchor_a.side == "M" else edge.anchor_b
        fa = edge.anchor_b if edge.anchor_a.side == "M" else edge.anchor_a
        m_node = anchor_node_name(ma)
        f_node = anchor_node_name(fa)
        length = wrist.tendon_lengths[edge_topology_key(edge)]
        attrs = {
            "name": f"{prefix}_wrist_{m_node}_to_{f_node}",
            "class": "string",
            "range": f"0.0 {length}",
            "stiffness": str(w.stiffness),
            "damping": str(w.damping),
            "springlength": str(length * w.pretension),
            "width": str(w.tendon_width),
            "rgba": (_hex_to_rgba(STRUCTURAL_TENDON_COLORS[index])
                     if color_structural_tendons else "0.25 0.55 0.9 1"),
        }
        spatial = ET.SubElement(tendon_el, "spatial", **attrs)
        ET.SubElement(spatial, "site", site=f"{prefix}_wrist_distal_{m_node}")
        ET.SubElement(spatial, "site", site=f"{prefix}_wrist_proximal_{f_node}")


def _add_tendons(
    root: ET.Element,
    compiled: CompiledMorphology,
    motor_tendon_ranges: Dict[str, MotorTendonRange] | None = None,
    color_structural_tendons: bool = False,
) -> None:
    morph = compiled.morph
    tendon_el = ET.SubElement(root, "tendon")

    for shoulder in compiled.shoulders:
        prefix = shoulder.side
        for index, edge in enumerate(shoulder.structural_edges):
            ma = edge.anchor_a if edge.anchor_a.side == "M" else edge.anchor_b
            fa = edge.anchor_b if edge.anchor_a.side == "M" else edge.anchor_a
            m_node = anchor_node_name(ma)
            f_node = anchor_node_name(fa)
            name = legacy_edge_name(prefix, m_node, f_node)
            length = shoulder.tendon_lengths[edge_topology_key(edge)]
            stiff, damp, pret, color = resolve_material_props(morph.tendons, edge)
            if name in morph.tendons.individual_overrides:
                mat = morph.tendons.individual_overrides[name]
                stiff = mat.stiffness if mat.stiffness is not None else stiff
                damp = mat.damping if mat.damping is not None else damp
                pret = mat.pretension if mat.pretension is not None else pret
                color = mat.color if mat.color is not None else color
            attrs = {
                "name": name,
                "class": "string",
                "range": f"0.0 {length}",
                "stiffness": str(stiff),
                "damping": str(damp),
                # Pretension: spring rest length = posed anchor distance * pretension
                # (pretension < 1 pre-tensions the tendon). Per-tendon via overrides.
                "springlength": str(length * pret),
            }
            # Debug palette overrides the per-tendon color when requested.
            attrs["rgba"] = (_hex_to_rgba(STRUCTURAL_TENDON_COLORS[index])
                             if color_structural_tendons else _color_to_rgba(color))
            spatial = ET.SubElement(tendon_el, "spatial", **attrs)
            ET.SubElement(spatial, "site", site=f"{shoulder.mobile_body}_{m_node}")
            ET.SubElement(spatial, "site", site=f"{shoulder.fixed_body}_{f_node}")

        if shoulder.wrist is not None:
            _add_wrist_tendons(tendon_el, shoulder, morph, color_structural_tendons)
        if morph.wing.bones is not None and morph.wing.bones.cables is not None:
            _add_wing_cables(tendon_el, shoulder.side, morph)

        for foot in morph.motors.feet:
            st = foot.station
            # Disk t{st} keeps its own rim/hinge but its tendon attaches to the
            # opposite foot anchor (t1<->t4 within the wing).
            foot_station = 4 if st == 1 else 1
            m_node = f"motor_t{foot_station}"
            disk = f"{prefix}_t{st}"
            disk_site = f"crank_disks_{disk}"
            tendon_name = f"{prefix}_motor_t{st}"
            spec = (motor_tendon_ranges or {}).get(tendon_name)
            if spec is not None:
                attrs = {
                    "name": tendon_name,
                    "class": "string",
                    "range": f"{spec.l_min} {spec.l_max}",
                    "stiffness": str(morph.motors.tendon_stiffness),
                    "damping": str(morph.motors.tendon_damping),
                    "springlength": str(spec.springlength),
                }
            else:
                length = derive_motor_length(shoulder, st, morph, foot_station=foot_station)
                attrs = {
                    "name": tendon_name,
                    "class": "string",
                    "range": f"0.0 {length}",
                    "solreflimit": _vec2(morph.motors.disk.solreflimit),
                }
            spatial = ET.SubElement(tendon_el, "spatial", **attrs)
            ET.SubElement(spatial, "site", site=f"{shoulder.mobile_body}_{m_node}")
            ET.SubElement(spatial, "site", site=disk_site)


def derive_motor_length(
    shoulder: CompiledShoulder, station: int, morph, foot_station: int | None = None
) -> float:
    foot_st = station if foot_station is None else foot_station
    m_node = shoulder.mobile_geom.nodes.get(f"motor_t{foot_st}", shoulder.mobile_geom.nodes[f"t{foot_st}"])
    foot_world = world_node(m_node, shoulder.mobile_pos, shoulder.mobile_quat)
    disk_name = f"{shoulder.side}_t{station}"
    disk = shoulder.disks[disk_name]
    pillar = np.array(disk["pillar_pos"], dtype=float)
    rim = np.array(disk["rim_pos"], dtype=float)
    tilt = morph.motors.disk.tilt_rad if shoulder.side == "L" else -morph.motors.disk.tilt_rad
    # ponytail: rest-length ignores disk pitch_rad (orbit pitch about Y). Only sets the
    # un-driven park length; pitch is mirror-symmetric so L/R stay balanced (sync +1.00,
    # validated). Add Ry(pitch) to the rim rotation below if the park drifts off-center.
    # Approximate rim world position from pillar + height + rotated rim
    z_disk = morph.motors.disk.pillar_height
    rim_world = pillar + np.array(
        [
            rim[0] * math.cos(tilt) - rim[2] * math.sin(tilt),
            rim[1],
            z_disk + rim[0] * math.sin(tilt) + rim[2] * math.cos(tilt),
        ]
    )
    return float(np.linalg.norm(foot_world - rim_world))


def _add_actuators(root: ET.Element, compiled: CompiledMorphology) -> None:
    spec = compiled.morph.motors.disk
    feet = compiled.morph.motors.feet
    ref_station = feet[0].station
    act = ET.SubElement(root, "actuator")
    for shoulder in compiled.shoulders:
        prefix = shoulder.side
        for foot in feet:
            st = foot.station
            attrs = {
                "name": f"{prefix}_motor_t{st}",
                "joint": f"{prefix}_t{st}_disk_hinge",
                "kv": str(spec.kv),
                "ctrlrange": _vec2(spec.ctrlrange),
            }
            # Crank phasing is baked into the actuator transmission so every drive
            # site (viewer, optimizer, validation) is consistent under one uniform
            # velocity command:
            #   - R shoulder is the Y-mirror of L -> gear -1 (+ctrl = L world motion).
            #   - the non-reference foot ALWAYS counter-rotates (gear -1) so the two
            #     cranks oppose and give the full reciprocating stroke.
            # crank_phase_lag is a crank-angle phase
            # lag applied to the t4 cranks at init (see runtime.crank_sync).
            gear = -1.0 if prefix == "R" else 1.0
            if st != ref_station:
                gear *= -1.0
            if gear != 1.0:
                attrs["gear"] = f"{gear:.6g}"
            ET.SubElement(act, "velocity", **attrs)
    _add_bone_actuators(act, compiled)


def _add_bone_actuators(act: ET.Element, compiled: CompiledMorphology) -> None:
    """Position servos for the avian wing's elbow, wrist and humerus twist.

    The tensegrity shoulder supplies the flap; these three hold the fold and the
    feathering against it. Servos rather than springs because the fold has to
    track the stroke phase, and because a stiff, critically damped setpoint is
    the cheapest way to keep a long wing from ringing the tendon network.
    """
    b = compiled.morph.wing.bones
    if b is None:
        return
    # Critically damped: overshoot on these hinges shakes the whole tendon
    # network, and a folding wing has no reason to ring.
    kv = 2.0 * math.sqrt(max(b.servo, 0.0) * max(b.armature, 1e-12))
    joints = [
        ("humerus_twist", b.twist_range_rad),
        # 1 DOF, deliberately: the elbow is the one plain hinge left in the wing.
        ("elbow", b.elbow_range_rad),
    ]
    if b.wrist is None:
        joints.append(("wrist", b.wrist_range_rad))
    for shoulder in compiled.shoulders:
        for name, rng in joints:
            ET.SubElement(
                act,
                "position",
                name=f"{shoulder.side}_{name}_servo",
                joint=f"{shoulder.side}_{name}",
                kp=f"{b.servo:.6g}",
                kv=f"{kv:.6g}",
                ctrlrange=_vec2(rng),
            )


def _vec3(v) -> str:
    if isinstance(v, np.ndarray):
        v = v.tolist()
    return f"{v[0]} {v[1]} {v[2]}"


def _vec4(v) -> str:
    if isinstance(v, np.ndarray):
        v = v.tolist()
    return " ".join(str(x) for x in v)


def _vec6(p1, p2) -> str:
    return f"{p1[0]} {p1[1]} {p1[2]} {p2[0]} {p2[1]} {p2[2]}"


def _vec2(v) -> str:
    return f"{v[0]} {v[1]}"


def _hex_to_rgba(color: str) -> str:
    color = color.lstrip("#")
    return " ".join(str(int(color[i : i + 2], 16) / 255.0) for i in (0, 2, 4)) + " 1"


def _color_to_rgba(color: str) -> str:
    """Normalize a tendon color to MJCF rgba. Accepts 'r g b [a]' or 'rrggbb' hex.

    ('#' can't be used in .tg -- it's a comment marker -- so hex has no leading #.)
    """
    text = str(color).strip()
    if " " in text:  # already space-separated rgba (pad alpha if omitted)
        parts = text.split()
        return " ".join(parts) if len(parts) >= 4 else " ".join(parts + ["1"])
    return _hex_to_rgba(text)  # 6-digit hex
