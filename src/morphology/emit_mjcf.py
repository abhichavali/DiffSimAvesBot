def emit_mjcf(
    compiled: CompiledMorphology,
    motor_tendon_ranges: Dict[str, MotorTendonRange] | None = None,
    color_structural_tendons: bool = False,
) -> str:
    morph = compiled.morph
    root = ET.Element("mujoco", model=morph.name)

    ET.SubElement(
        root,
        "compiler",
        angle="radian",
        meshdir=morph.world.meshdir,
        autolimits="true",
    )
    ET.SubElement(
        root,
        "option",
        gravity=_vec3(morph.world.gravity),
        timestep=str(morph.world.timestep),
        integrator=morph.world.integrator,
    )
    _add_visual(root)
    _add_assets(root, morph)
    _add_defaults(root, morph)
    worldbody = ET.SubElement(root, "worldbody")
    _emit_scene_environment(worldbody)

    for shoulder in compiled.shoulders:
        _emit_shoulder(worldbody, shoulder, morph, compiled)

    _add_tendons(root, compiled, motor_tendon_ranges, color_structural_tendons)
    _add_equalities(root, morph)
    _add_actuators(root, compiled)

    ET.indent(root, space="  ")
    return ET.tostring(root, encoding="unicode", xml_declaration=True)


def _add_visual(parent: ET.Element) -> None:
    visual = ET.SubElement(parent, "visual")
    ET.SubElement(visual, "headlight", diffuse="0.6 0.6 0.6", ambient="0.3 0.3 0.3", specular="0 0 0")
    ET.SubElement(visual, "rgba", haze="0.15 0.25 0.35 1")
    # offwidth/offheight raise the offscreen framebuffer above MuJoCo's 640x480
    # default so the headless Renderer (mjx render.py / live_viewer.py) can render
    # up to 1080p without "Image width > framebuffer width" errors.
    ET.SubElement(
        visual, "global", azimuth="160", elevation="-20", offwidth="1920", offheight="1080"
    )


def _add_assets(root: ET.Element, morph) -> None:
    asset = ET.SubElement(root, "asset")
    ET.SubElement(
        asset,
        "texture",
        type="skybox",
        builtin="gradient",
        rgb1="0.3 0.5 0.7",
        rgb2="0 0 0",
        width="512",
        height="3072",
    )
    ET.SubElement(
        asset,
        "texture",
        type="2d",
        name="groundplane",
        builtin="checker",
        mark="edge",
        rgb1="0.2 0.3 0.4",
        rgb2="0.1 0.2 0.3",
        markrgb="0.8 0.8 0.8",
        width="300",
        height="300",
    )
    ET.SubElement(
        asset,
        "material",
        name="groundplane",
        texture="groundplane",
        texuniform="true",
        texrepeat="5 5",
        reflectance="0.2",
    )
    ET.SubElement(asset, "mesh", file=morph.wing.mesh_file)
    ET.SubElement(asset, "material", name="wing_material", rgba="0.615686 0.811765 0.929412 1")


def _emit_scene_environment(worldbody: ET.Element) -> None:
    """Floor + directional light (matches legacy autogenerated_scene wrapper)."""
    ET.SubElement(worldbody, "light", pos="0 0 3.5", dir="0 0 -1", directional="true")
    ET.SubElement(
        worldbody,
        "geom",
        name="floor",
        type="plane",
        size="0 0 0.05",
        pos="0 0 0",
        material="groundplane",
    )


def _add_defaults(root: ET.Element, morph) -> None:
    default_el = ET.SubElement(root, "default")
    sj = ET.SubElement(default_el, "default", {"class": "shoulder-joint"})
    ET.SubElement(sj, "joint", frictionloss="0.1", armature="0.005")
    vis = ET.SubElement(sj, "default", {"class": "visual"})
    ET.SubElement(vis, "geom", type="mesh", contype="0", conaffinity="0", group="2")
    col = ET.SubElement(sj, "default", {"class": "collision"})
    ET.SubElement(col, "geom", group="3")
    td = morph.tendons.defaults
    string_def = ET.SubElement(default_el, "default", {"class": "string"})
    ET.SubElement(string_def, "tendon", width=str(td.width), rgba="0.8 0.2 0.2 1", limited="true")


def _emit_shoulder(
    worldbody: ET.Element,
    shoulder: CompiledShoulder,
    morph,
    compiled: CompiledMorphology,
) -> None:
    prefix = shoulder.side
    mobile_el = _emit_strut_body(
        worldbody,
        shoulder.mobile_body,
        shoulder.mobile_geom,
        shoulder.mobile_pos,
        shoulder.mobile_quat,
        joint="free",
    )
    _emit_strut_body(
        worldbody,
        shoulder.fixed_body,
        shoulder.fixed_geom,
        shoulder.fixed_pos,
        shoulder.fixed_quat,
        joint="fixed",
    )
    _emit_wing(mobile_el, shoulder, morph, compiled)
    for disk_name, disk in shoulder.disks.items():
        _emit_crank_disk(worldbody, disk_name, disk, morph)


def _emit_strut_body(
    parent: ET.Element,
    body_name: str,
    geom,
    pos: np.ndarray,
    quat: np.ndarray,
    joint: str,
) -> ET.Element:
    body = ET.SubElement(
        parent,
        "body",
        name=body_name,
        pos=_vec3(pos),
        childclass="shoulder-joint",
        quat=_vec4(quat),
    )
    if joint == "free":
        ET.SubElement(body, "freejoint", name=f"{body_name}_freejoint")

    arc_r, arc_m = geom.arc_rod
    rung_r, rung_m = geom.rung_rod

    for i, (a, b) in enumerate(geom.rung_rod_pairs):
        _capsule(body, f"{body_name}_rod_{i}", geom.nodes[a], geom.nodes[b], rung_r, rung_m)

    base = len(geom.rung_rod_pairs)
    for i, (a, b) in enumerate(geom.arc_rod_pairs):
        _capsule(body, f"{body_name}_rod_{base + i}", geom.nodes[a], geom.nodes[b], arc_r, arc_m)

    # Rigid bridging rods from a motor foot edge to an inset motor anchor.
    # Mass tracks the arc-rod linear density so the inset strut is physical.
    if geom.motor_rod_pairs:
        ref_a, ref_b = geom.arc_rod_pairs[0]
        ref_len = float(np.linalg.norm(geom.nodes[ref_a] - geom.nodes[ref_b]))
        lin_density = arc_m / ref_len if ref_len > 1e-9 else 0.0
        for i, (a, b) in enumerate(geom.motor_rod_pairs):
            length = float(np.linalg.norm(geom.nodes[a] - geom.nodes[b]))
            _capsule(
                body,
                f"{body_name}_motor_rod_{i}",
                geom.nodes[a],
                geom.nodes[b],
                arc_r,
                lin_density * length,
            )

    attachment_nodes = set()
    for a, b in geom.rung_rod_pairs:
        attachment_nodes.add(a)
        attachment_nodes.add(b)
    for a, b in geom.arc_rod_pairs:
        attachment_nodes.add(a)
        attachment_nodes.add(b)
    for name in geom.nodes:
        if name.startswith("motor_"):
            attachment_nodes.add(name)

    for node_name, node_pos in geom.nodes.items():
        if node_name.startswith("c") and node_name[1:].isdigit():
            _site(body, body_name, node_name, node_pos, geom.site_quats.get(node_name))
        elif node_name in attachment_nodes:
            _site(body, body_name, node_name, node_pos, geom.site_quats.get(node_name))

    return body


def _emit_wing(parent: ET.Element, shoulder: CompiledShoulder, morph, compiled: CompiledMorphology) -> None:
    # Deferred import: wing_geometry -> morphology_runtime -> morphology.compile
    # -> emit_mjcf would cycle at module level.
    from utils.aero.wing_geometry import _resolve_wing_mesh_path, load_wing_geometry_from_stl

    scale = morph.world.scale
    rod = morph.wing.rod_length * scale
    arm = morph.wing.mount_arm * scale
    pitch = morph.wing.pitch
    prefix = shoulder.side
    mount_z = rod + 0.000096
    # The pitch-mount arms (T-pose) hook the wing at (±arm, mount_z). World-up is
    # the body y-axis here (verified numerically: world-up = ∓y), i.e. along the
    # arm reach — so a pure VERTICAL displacement of the wing is an offset in y,
    # not z. Pushing the mesh out past the hub (|y| = arm + drop) lowers the wing
    # in world so the hook rides higher up the wing (toward the top); the arms and
    # hub stay fixed. Absolute metres (the STL is not world-scaled).
    wing_attach_drop = 0.035  # +down in world; flip sign to raise the wing
    mesh_y = (1.0 if prefix == "L" else -1.0) * (arm + wing_attach_drop)

    wing = ET.SubElement(
        parent,
        "body",
        name=f"{prefix}_wing",
        pos=_vec3(shoulder.mobile_geom.midpoint),
        childclass="shoulder-joint",
        quat="1.0 0.0 0.0 0.0",
    )
    # Wing-body frame (verified numerically): +z = span, laterally outboard for
    # both sides (the mesh long axis); ±y = world down (+y on L, -y on R); the
    # stroke sweeps about world-vertical. Pitch must rotate about the SPAN, so
    # the hinge is body z (mirror-signed so +q is the same world sense L/R).
    pitch_axis = "0.0 0.0 1.0" if prefix == "L" else "0.0 0.0 -1.0"
    ET.SubElement(
        wing,
        "joint",
        name=f"{prefix}_wing_pitch",
        type="hinge",
        axis=pitch_axis,
        limited="true",
        range=_vec2(pitch.range_rad),
        springref="0.0",
        # Passively free: one-sided pitch deadbands are applied at runtime.
        stiffness="0",
        damping="0",
        # Override the shoulder-joint class default (frictionloss=0.1): 0.1 N m
        # of dry friction is ~100x the aero pitch torque of the 0.135 g wing and
        # stiction-locks the hinge (wings park at arbitrary leans).
        frictionloss="0",
        armature=str(pitch.armature),
        ref=str(pitch.initial_rad),
    )
    # The blade-element model (utils/aero) is expressed in the root-SITE frame
    # with span along -y (strips at y<0... lever=[0,-r,0]), chord along z, and
    # the pitching moment about y. The site quat maps that convention onto the
    # body: y_site = -z_body (span), x_site/z_site in the chord/normal plane.
    # Without it the model's pitching moment lands perpendicular to the hinge
    # and the pitch DOF receives identically zero. BOTH sides use the same
    # body-frame quat: the aerodynamics_left/right sign tables (s.cof etc.)
    # carry the full mirror, so giving R a mirrored frame double-mirrors and
    # produces exactly anti-symmetric pitch torque (tau_qR = -tau_qL, wings
    # lock into opposite leans) — verified against hand-computed flat-plate
    # weathervane signs for translation and rotation stroke kinematics.
    root_quat = "0.70710678 -0.70710678 0.0 0.0"
    ET.SubElement(
        wing,
        "site",
        name=f"{prefix}_wing_Root_Site",
        type="sphere",
        pos="0 0 0",
        quat=root_quat,
        size="0.006",
        rgba="1.0 1.0 0.0 1",
        group="3",
    )
    ET.SubElement(
        wing,
        "geom",
        name=f"{prefix}_wing_pitch_rod",
        type="cylinder",
        fromto=f"0 0 0 0 0 {rod}",
        size="0.0025",
        mass="6e-06",
        rgba="0.95 0.45 0.1 1",
        **{"class": "visual", "contype": "0", "conaffinity": "0", "group": "2"},
    )
    y_sign = 1.0 if prefix == "L" else -1.0
    ET.SubElement(
        wing,
        "geom",
        name=f"{prefix}_wing_pitch_mount",
        type="capsule",
        fromto=f"0 0 {rod} 0 {y_sign * arm} {mount_z}",
        size="0.0016",
        mass="5e-06",
        rgba="0.95 0.45 0.1 1",
        **{"class": "visual", "contype": "0", "conaffinity": "0", "group": "2"},
    )
    ET.SubElement(
        wing,
        "geom",
        name=f"{prefix}_wing_mount_hub",
        type="sphere",
        pos=f"0 {y_sign * arm} {mount_z}",
        size="0.0026",
        mass="4e-06",
        rgba="0.95 0.45 0.1 1",
        contype="0",
        conaffinity="0",
        group="2",
    )
    wing_quat = "0.5 -0.5 -0.5 -0.5" if prefix == "L" else "0.5 0.5 -0.5 0.5"
    mesh_attrs = {
        "type": "mesh",
        "mesh": "wing",
        "material": "wing_material",
        "pos": f"0 {mesh_y} {mount_z}",
        "quat": wing_quat,
        # Explicit mass: without it the STL takes MuJoCo's default density
        # (1000 kg/m^3 -> ~17.7 g) and the wing is ~140x over its real
        # 0.13-0.14 g, burying aero pitch torques under inertia.
        "mass": "0.00012",
    }
    # Visual-only: the wing carries no collision geom. The flapper never contacts
    # anything, and a mesh collider forces MJX onto its slow/inaccurate convex-mesh
    # path (and gives the worst contact gradients for autodiff).
    ET.SubElement(wing, "geom", **{**mesh_attrs, "class": "visual", "group": "2"})

    # Blade strip sites sit on the span (= hinge) axis at the exact radii the
    # blade-element model assumes for its levers: (i+0.5)/N * STL span,
    # measured from the root site, unscaled (the mesh is not world-scaled).
    num_blades = morph.wing.aero.blades
    mesh_path = _resolve_wing_mesh_path(morph.wing.mesh_file, morph.world.meshdir)
    wing_length = load_wing_geometry_from_stl(mesh_path, num_blades=num_blades).length
    blade_span = wing_length / num_blades
    for blade_index in range(num_blades):
        pos_z = (blade_index + 0.5) * blade_span
        t = 0.5 if num_blades == 1 else blade_index / (num_blades - 1)
        red = 1.0 - t
        green = 0.25 + 0.5 * (1.0 - abs(2.0 * t - 1.0))
        blue = t
        ET.SubElement(
            wing,
            "site",
            name=f"{prefix}_wing_aero_blade_{blade_index + 1:02d}",
            type="sphere",
            pos=f"0 0 {pos_z}",
            size="0.006",
            rgba=f"{red:.3f} {green:.3f} {blue:.3f} 1",
            group="3",
        )


def _capsule(parent, name, p1, p2, radius, mass):
    # contype=2/conaffinity=1 is the standard self-collision filter: strut-vs-strut
    # is masked (2&1 == 0 both ways) so the interleaved tensegrity capsules don't
    # spawn hundreds of spurious MJX candidate pairs, while strut-vs-floor
    # (contype 1) still collides. The struts never actually touch in this rig, so
    # this only removes wasted broad-phase work (and gradient noise).
    ET.SubElement(
        parent,
        "geom",
        name=name,
        type="capsule",
        fromto=_vec6(p1, p2),
        size=str(radius),
        mass=str(mass),
        rgba="0.5 0.5 0.5 1",
        contype="2",
        conaffinity="1",
    )


def _site(parent, body_name, node_name, pos, quat=None):
    attrs = {
        "name": f"{body_name}_{node_name}",
        "pos": _vec3(pos),
        "size": "0.002",
        "rgba": "0.2 0.8 0.2 1",
        "group": "3",
    }
    if quat is not None:
        attrs["quat"] = _vec4(quat)
    ET.SubElement(parent, "site", **attrs)


def _emit_crank_disk(parent: ET.Element, disk_name: str, disk: Dict[str, Any], morph) -> None:
    spec = morph.motors.disk
    disk_rgba = MATPLOTLIB_BLUE_RGBA if disk_name.endswith("_t1") else MATPLOTLIB_ORANGE_RGBA
    pillar = ET.SubElement(
        parent,
        "body",
        name=f"{disk_name}_pillar",
        pos=_vec3(disk["pillar_pos"]),
    )
    ET.SubElement(
        pillar,
        "inertial",
        pos="0 0 0.11",
        mass="0.1",
        fullinertia="1e-4 1e-4 1e-4 0 0 0",
    )
    ET.SubElement(
        pillar,
        "geom",
        name=f"{disk_name}_pillar_geom",
        type="cylinder",
        size=f"{spec.pillar_radius} {spec.pillar_height / 2}",
        pos=f"0 0 {spec.pillar_height / 2}",
        rgba="0.4 0.4 0.4 0.8",
        contype="0",
        conaffinity="0",
        group="2",
    )
    euler = disk["euler"]
    disk_body = ET.SubElement(
        pillar,
        "body",
        name=f"{disk_name}_disk",
        pos=f"0 0 {spec.pillar_height}",
        euler=_vec3(euler),
    )
    ET.SubElement(
        disk_body,
        "joint",
        name=f"{disk_name}_disk_hinge",
        type="hinge",
        axis="0 0 1",
        damping="0.001",
        armature="0.0001",
    )
    ET.SubElement(
        disk_body,
        "inertial",
        pos="0 0 0",
        mass="0.005",
        fullinertia="1e-6 2e-6 1e-6 0 0 0",
    )
    ET.SubElement(
        disk_body,
        "geom",
        name=f"{disk_name}_disk_geom",
        type="cylinder",
        size=f"{spec.radius} {spec.disk_half_height}",
        rgba=disk_rgba,
        contype="0",
        conaffinity="0",
        group="2",
    )
    rim = disk["rim_pos"]
    # If the tendon pin sits past the disk rim (crank_throw > radius), draw a rigid
    # crank arm from the hinge axis out to the pin so the lever is physical.
    pin_r = float(np.linalg.norm(rim[:2]))
    if pin_r > spec.radius + 1e-6:
        ET.SubElement(
            disk_body,
            "geom",
            name=f"{disk_name}_crank_arm",
            type="capsule",
            fromto=f"0 0 0 {rim[0]} {rim[1]} {rim[2]}",
            size="0.0025",
            rgba=disk_rgba,
            contype="0",
            conaffinity="0",
            group="2",
        )
    ET.SubElement(
        disk_body,
        "site",
        name=f"crank_disks_{disk_name}",
        pos=_vec3(rim),
        size="0.002",
        rgba=disk["rim_rgba"],
        group="3",
    )


def _add_tendons(
    root: ET.Element,
    compiled: CompiledMorphology,
    motor_tendon_ranges: Dict[str, MotorTendonRange] | None = None,
    color_structural_tendons: bool = False,
) -> None:
    morph = compiled.morph
    tendon_el = ET.SubElement(root, "tendon")

    for shoulder in compiled.shoulders:
        prefix = shoulder.side
        for index, edge in enumerate(shoulder.structural_edges):
            ma = edge.anchor_a if edge.anchor_a.side == "M" else edge.anchor_b
            fa = edge.anchor_b if edge.anchor_a.side == "M" else edge.anchor_a
            m_node = anchor_node_name(ma)
            f_node = anchor_node_name(fa)
            name = legacy_edge_name(prefix, m_node, f_node)
            length = shoulder.tendon_lengths[edge_topology_key(edge)]
            stiff, damp, pret = resolve_material_props(morph.tendons, edge)
            attrs = {
                "name": name,
                "class": "string",
                "range": f"0.0 {length}",
                "stiffness": str(stiff),
                "damping": str(damp),
            }
            if color_structural_tendons:
                attrs["rgba"] = _hex_to_rgba(STRUCTURAL_TENDON_COLORS[index])
            spatial = ET.SubElement(tendon_el, "spatial", **attrs)
            ET.SubElement(spatial, "site", site=f"{shoulder.mobile_body}_{m_node}")
            ET.SubElement(spatial, "site", site=f"{shoulder.fixed_body}_{f_node}")

        for foot in morph.motors.feet:
            st = foot.station
            # Contralateral actuation: disk t{st} keeps its own rim/hinge but its
            # tendon attaches to the OPPOSITE foot anchor (t1<->t4 within the wing).
            foot_station = 4 if st == 1 else 1
            m_node = f"motor_t{foot_station}"
            disk = f"{prefix}_t{st}"
            disk_site = f"crank_disks_{disk}"
            tendon_name = f"{prefix}_motor_t{st}"
            spec = (motor_tendon_ranges or {}).get(tendon_name)
            if spec is not None:
                attrs = {
                    "name": tendon_name,
                    "class": "string",
                    "range": f"{spec.l_min} {spec.l_max}",
                    "stiffness": str(morph.motors.tendon_stiffness),
                    "damping": str(morph.motors.tendon_damping),
                    "springlength": str(spec.springlength),
                }
            else:
                length = derive_motor_length(shoulder, st, morph, foot_station=foot_station)
                attrs = {
                    "name": tendon_name,
                    "class": "string",
                    "range": f"0.0 {length}",
                    "solreflimit": _vec2(morph.motors.disk.solreflimit),
                }
            spatial = ET.SubElement(tendon_el, "spatial", **attrs)
            ET.SubElement(spatial, "site", site=f"{shoulder.mobile_body}_{m_node}")
            ET.SubElement(spatial, "site", site=disk_site)


def derive_motor_length(
    shoulder: CompiledShoulder, station: int, morph, foot_station: int | None = None
) -> float:
    foot_st = station if foot_station is None else foot_station
    m_node = shoulder.mobile_geom.nodes.get(f"motor_t{foot_st}", shoulder.mobile_geom.nodes[f"t{foot_st}"])
    foot_world = world_node(m_node, shoulder.mobile_pos, shoulder.mobile_quat)
    disk_name = f"{shoulder.side}_t{station}"
    disk = shoulder.disks[disk_name]
    pillar = np.array(disk["pillar_pos"], dtype=float)
    rim = np.array(disk["rim_pos"], dtype=float)
    tilt = morph.motors.disk.tilt_rad if shoulder.side == "L" else -morph.motors.disk.tilt_rad
    # ponytail: rest-length ignores disk pitch_rad (orbit pitch about Y). Only sets the
    # un-driven park length; pitch is mirror-symmetric so L/R stay balanced (sync +1.00,
    # validated). Add Ry(pitch) to the rim rotation below if the park drifts off-center.
    # Approximate rim world position from pillar + height + rotated rim
    z_disk = morph.motors.disk.pillar_height
    rim_world = pillar + np.array(
        [
            rim[0] * math.cos(tilt) - rim[2] * math.sin(tilt),
            rim[1],
            z_disk + rim[0] * math.sin(tilt) + rim[2] * math.cos(tilt),
        ]
    )
    return float(np.linalg.norm(foot_world - rim_world))


def _add_equalities(root: ET.Element, morph) -> None:
    from morphology.motor_drive import disk_equality_polycoef

    eq = ET.SubElement(root, "equality")
    couple = morph.mirror.couple
    if morph.motors.couple_mobile_disk_hinges:
        polycoef = disk_equality_polycoef(morph)
        feet = morph.motors.feet
        for prefix in ("L", "R"):
            ET.SubElement(
                eq,
                "joint",
                joint1=f"{prefix}_t{feet[0].station}_disk_hinge",
                joint2=f"{prefix}_t{feet[1].station}_disk_hinge",
                polycoef=polycoef,
            )
    # NOTE: no L/R wing-pitch equality. Locking q_L to q_R cancels the effective
    # pitch torque for L/R-symmetric loads (gravity, aero, inertia) and pins the
    # passive pitch — each wing must weathervane independently. L/R flap sync is
    # already enforced by the disk locks below.
    if couple.couple_left_right_disks:
        # Lock the left/right crank disks together so the two shoulders stay
        # phase-locked under asymmetric aero load. The Y-mirror's σ-symmetry swaps
        # stations 1<->4, so the physically corresponding cranks are CROSSED
        # (L_t1 mirrors R_t4, L_t4 mirrors R_t1). Coupling same-station instead
        # locks the wrong cranks and forces the wings out of phase.
        # +1 keeps the crossed cranks in phase (ipsilateral); -1 locks them
        # anti-phase so the wings alternate (contralateral).
        disk_coef = "-1.0" if couple.contralateral_wings else "1.0"
        feet = morph.motors.feet
        for left_foot, right_foot in zip(feet, reversed(feet)):
            ET.SubElement(
                eq,
                "joint",
                joint1=f"L_t{left_foot.station}_disk_hinge",
                joint2=f"R_t{right_foot.station}_disk_hinge",
                polycoef=f"0.0 {disk_coef} 0.0 0.0 0.0",
            )


def _add_actuators(root: ET.Element, compiled: CompiledMorphology) -> None:
    spec = compiled.morph.motors.disk
    couple = compiled.morph.mirror.couple
    act = ET.SubElement(root, "actuator")
    for shoulder in compiled.shoulders:
        prefix = shoulder.side
        for foot in compiled.morph.motors.feet:
            st = foot.station
            attrs = {
                "name": f"{prefix}_motor_t{st}",
                "joint": f"{prefix}_t{st}_disk_hinge",
                "kv": str(spec.kv),
                "ctrlrange": _vec2(spec.ctrlrange),
            }
            # Y-mirrored shoulder: flip R crank actuators so +ctrl matches L world
            # motion (ipsilateral). Contralateral keeps the mirror (+1) so R drives
            # the opposite world direction and the wings alternate.
            if prefix == "R" and couple.inphase_left_right_drive:
                attrs["gear"] = "1" if couple.contralateral_wings else "-1"
            ET.SubElement(act, "velocity", **attrs)


def _vec3(v) -> str:
    if isinstance(v, np.ndarray):
        v = v.tolist()
    return f"{v[0]} {v[1]} {v[2]}"


def _vec4(v) -> str:
    if isinstance(v, np.ndarray):
        v = v.tolist()
    return " ".join(str(x) for x in v)


def _vec6(p1, p2) -> str:
    return f"{p1[0]} {p1[1]} {p1[2]} {p2[0]} {p2[1]} {p2[2]}"


def _vec2(v) -> str:
    return f"{v[0]} {v[1]}"


def _hex_to_rgba(color: str) -> str:
    color = color.lstrip("#")
    return " ".join(str(int(color[i : i + 2], 16) / 255.0) for i in (0, 2, 4)) + " 1"
